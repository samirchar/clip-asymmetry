_TEXT_ENCODERS_GRID = ["Femto", "Atto", "Nano", "Tiny", "Base", "Giant"]


def _learning_curves(data, vision_encoder="ViT-Colossal-16"):
    """2×2 learning curves for one vision encoder.

    Top row: train loss, bottom row: ImageNet ZS val top-1.
    Columns: CC12M / CC3M. Colored by text encoder. X-axis is epoch.
    """
    combined = _load_learning_curves_frame(vision_encoder, _TEXT_ENCODERS_GRID)

    tp, tl = data["text_palette"], data["text_labels"]
    arch = data["architectures"]
    text_name_to_params = dict(
        arch[["text_name", "text_params"]].drop_duplicates().values
    )

    datasets = ["cc12m", "cc3m"]
    metrics = [
        ("train/loss", "Train Loss"),
        ("val/imagenet-zeroshot-val-top1", "ImageNet ZS Val Top-1 (%)"),
    ]

    fig, axes = plt.subplots(2, 2, figsize=(TEXTWIDTH, 4.8))

    for row, (metric_col, metric_label) in enumerate(metrics):
        for col, ds in enumerate(datasets):
            ax = axes[row, col]
            subset = combined[
                (combined["dataset"] == ds) & (combined[metric_col].notna())
            ].sort_values("epoch")

            for text_name in _TEXT_ENCODERS_GRID:
                text_data = subset[subset["text_name"] == text_name]
                if text_data.empty:
                    continue
                t_params = text_name_to_params.get(text_name)
                color = tp.get(t_params, "#999999")
                ax.plot(
                    text_data["epoch"], text_data[metric_col],
                    linewidth=0.9, color=color,
                )

            ax.set_xlabel("Epoch" if row == 1 else "")
            ax.set_ylabel(metric_label if col == 0 else "")
            if row == 1:
                ax.yaxis.set_major_formatter(mpl.ticker.PercentFormatter(1.0, decimals=0, symbol=None))
            if row == 0:
                ax.set_title(ds.upper())

    # Shared legend at the bottom
    handles = []
    for text_name in _TEXT_ENCODERS_GRID:
        t_params = text_name_to_params.get(text_name)
        if t_params and t_params in tp:
            handles.append(
                mpl.lines.Line2D([], [], color=tp[t_params], linewidth=0.9,
                                 label=tl.get(t_params, text_name))
            )
    fig.legend(
        handles=handles, title="Text Encoder",
        loc="lower center", ncol=len(handles), framealpha=0.8,
        bbox_to_anchor=(0.5, -0.02), fontsize=7, title_fontsize=8,
    )

    label_panels(axes)
    fig.tight_layout(rect=[0, 0.08, 1, 1])
    return fig


