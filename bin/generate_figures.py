def _scaling_lineplot(data, super_task, x_col, hue_col, x_label, hue_label, palette, labels, sharey=False):
    """Generate 1×2 grid (cc12m | cc3m) scaling line plot."""
    bench = data["benchmarks"]
    fig, axes = plt.subplots(1, 2, figsize=SIZES["full_wide"], sharey=sharey)

    all_hue_vals = None
    for idx, (ax, dataset) in enumerate(zip(axes, ["cc12m", "cc3m"])):
        q = _base_query(data, dataset, super_task)
        plot_data = bench.query(q)

        # Filter palette/labels to values present in data
        present_hue_vals, plot_palette = _present_palette(plot_data[hue_col], palette)
        if all_hue_vals is None:
            all_hue_vals = present_hue_vals

        sns.lineplot(
            data=plot_data, x=x_col, y="preferred_metric_value",
            hue=hue_col, ax=ax, marker="o", errorbar=None,
            palette=plot_palette, hue_order=present_hue_vals,
        )
        ax.set_xlabel(f"{x_label} (M)")
        ax.set_ylabel("Avg Performance (%)" if idx == 0 else "")
        ax.yaxis.set_major_formatter(mpl.ticker.PercentFormatter(1.0, decimals=0, symbol=None))
        ax.xaxis.set_major_formatter(millions_formatter())
        ax.set_title(dataset.upper())
        ax.legend().remove()

