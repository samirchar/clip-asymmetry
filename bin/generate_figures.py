# ── Small shared helpers ───────────────────────────────
def _present_palette(values, palette):
    """(sorted unique values present, palette filtered to just those keys)."""
    present = sorted(values.unique())
    return present, {k: palette[k] for k in present if k in palette}


def _encoder_name_maps(q_data):
    """(vision_params→name, text_params→name) lookups for heatmap axis labels."""
    return (
        q_data.drop_duplicates("vision_params").set_index("vision_params")["vision_name"].to_dict(),
        q_data.drop_duplicates("text_params").set_index("text_params")["text_name"].to_dict(),
    )


def _encoder_tick_labels(keys, name_map):
    """Encoder axis tick labels, e.g. ``['Base (86M)', ...]``."""
    return [f"{name_map.get(k, '')} ({format_params_axis(k)}M)" for k in keys]


