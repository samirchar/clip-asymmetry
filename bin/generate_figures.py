def _zs_cc12m_model_grid(data):
    """Average CC12M zero-shot observations by vision/text encoder size."""
    q = data["benchmarks"].query(_base_query(data, "cc12m", "zeroshot"))
    return (q.groupby(["model_fullname", "vision_params", "text_params"])
            .agg(avg_perf=("preferred_metric_value", "mean")).reset_index())


def _zs_ceiling_coefficients():
    """Load cached coefficients for the saturating-ceiling mismatch model."""
    path = Path(__file__).resolve().parents[1] / "data/analysis/zs_perf_regression_params.json"
    with path.open() as f:
        return json.load(f)["ceiling_model_coefficients"]


def _zs_ceiling_predict(nv_m, nt_m, coeffs):
    """Eq. 1 prediction with parameter counts in millions."""
    return ((coeffs["beta0"] + coeffs["beta1"] * np.log10(nv_m))
            * (1 - np.exp(-coeffs["k_text"] * nt_m))
            * np.exp(-coeffs["c_mismatch"] * (np.log10(nv_m / nt_m)) ** 2))


def _zs_fit_surface_contours(data):
    """Predicted response surface as iso-performance contours plus observations.

    Eq. 1 is evaluated over a range padded 1.6x beyond the observed grid so the
    contours fill the frame; the region outside the data is a model extrapolation.
    """
    mp = _zs_cc12m_model_grid(data)
    coeffs = _zs_ceiling_coefficients()
    nv = np.logspace(np.log10(mp["vision_params"].min() / 1e6 / 1.4),
                     np.log10(mp["vision_params"].max() / 1e6 * 1.7), 240)
    nt = np.logspace(np.log10(mp["text_params"].min() / 1e6 / 1.4),
                     np.log10(mp["text_params"].max() / 1e6 * 2.3), 240)
    nv_grid, nt_grid = np.meshgrid(nv, nt)
    pred = _zs_ceiling_predict(nv_grid, nt_grid, coeffs)

    lo = np.floor(pred.min() * 100) / 100
    hi = np.ceil(pred.max() * 100) / 100
    levels = np.arange(lo, hi + 1e-9, 0.01)

    fig, ax = plt.subplots(figsize=(THEME.textwidth * 0.44, 2.12))
    ax.contour(
        nv_grid * 1e6, nt_grid * 1e6, pred, levels=levels,
        cmap="viridis", linewidths=0.7,
    )
    ax.scatter(
        mp["vision_params"], mp["text_params"], c=mp["avg_perf"],
        cmap="viridis", vmin=lo, vmax=hi, s=30,
        edgecolor="black", linewidth=0.6, zorder=3,
    )

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Vision Params (M)")
    ax.set_ylabel("Text Params (M)")
    ax.xaxis.set_major_formatter(millions_formatter())
    ax.yaxis.set_major_formatter(millions_formatter())
    ax.tick_params(labelsize=THEME.fs_annot)
    ax.set_xlim(nv.min() * 1e6, nv.max() * 1e6)
    ax.set_ylim(nt.min() * 1e6, nt.max() * 1e6)

    sm = mpl.cm.ScalarMappable(cmap="viridis",
                               norm=mpl.colors.Normalize(vmin=lo, vmax=hi))
    cbar = fig.colorbar(sm, ax=ax)
    cbar.set_label("Avg Performance (%)")
    cbar.ax.yaxis.set_major_formatter(mpl.ticker.PercentFormatter(1.0, decimals=0, symbol=None))
    cbar.ax.tick_params(labelsize=THEME.fs_annot)
    fig.tight_layout()
    return fig


