def _wd_ablation_panel(ax, data, pretrain_dataset="cc12m", label_values=True,
                       tag=None, baseline_label="Base--Giant",
                       reference_vision_name="Base",
                       reference_model="ViT-B-16--Tiny",
                       reference_label="Base--Tiny",
                       scenarios=("text", "vision", "joint"), pt_s=25,
                       text_color=None):
    """Effective-WD ablation: text-only / vision-only / joint WD vs avg ZS.

    Three lines share the baseline (joint WD 0.5) at the left, then rise to the
    two ablated levels (effective WD 0.75 and 1.0). A dashed line marks the best
    same-vision architecture (the reference). Runs still being evaluated are
    simply absent and the lines connect whatever is available. ``label_values``
    prints the per-point ZS values (off for narrow panels).

    ``tag`` selects the run family (default Base--Giant ``{dataset}_wd_ablation``);
    ``baseline_label`` / ``reference_*`` swap the annotations and reference
    architecture for the Giant--Giant replication. ``scenarios`` selects which
    WD arms to draw (e.g. ``("text", "vision")`` drops the joint arm).
    """
    tag = tag or f"{pretrain_dataset}_wd_ablation"
    bench = data["benchmarks"]
    ct = data["CHECKPOINT_TYPE"]

    # --- Assemble the ablated runs (avg ZS per run) ---
    # Exact-token tag match: keep the base 'cc12m_wd_ablation' family
    # separate from 'cc12m_wd_ablation_giant'.
    tag_mask = bench["wandb_tags"].str.contains(
        rf"(?:^|\|){re.escape(tag)}(?:\||$)", regex=True, na=False)
    abl = bench[tag_mask].query(
        f"pretrain_dataset == '{pretrain_dataset}' and super_task == 'zeroshot' and "
        f"checkpoint_type == '{ct}'"
    )
    # Exclude the old-recipe reference (different local_loss/gather_with_grad),
    # which is not a valid same-recipe baseline for this ablation.
    abl = abl[~abl["run_name"].str.contains("_1772044155", na=False)]
    avg_zs = abl.groupby("run_name")["preferred_metric_value"].mean().mul(100)

    configs = _load_run_configs()
    records = []
    for run_name, zs in avg_zs.items():
        eff_t, eff_v = _wd_effective(run_name, configs.get(run_name))
        scenario, level = _wd_classify(eff_t, eff_v)
        if scenario is None:
            continue
        records.append({"scenario": scenario, "level": level, "zs": zs})
    abl_df = pd.DataFrame(records)

    # --- Baseline avg ZS (shared origin at WD 0.5) ---
    baseline_rows = abl_df[abl_df["scenario"] == "baseline"]
    baseline_zs = baseline_rows["zs"].mean() if len(baseline_rows) else None

    # --- Reference: best same-vision architecture, for the reference line ---
    arch_q = _base_query(data, pretrain_dataset, "zeroshot")
    base_arch = (
        bench.query(arch_q)
        .query(f"vision_name == '{reference_vision_name}'")
        .groupby("model")["preferred_metric_value"].mean().mul(100)
    )
    base_tiny_zs = base_arch.get(reference_model)

    # --- Colors: consistent with paper (vision=Blues, text=RdPu), joint=neutral ---
    # ``text_color`` overrides the default text-modality accent (still an RdPu-ramp
    # colour) for figures that need a lighter text-only line.
    style = {k: list(v) for k, v in _WD_ABLATION_STYLE.items()}
    style["text"][0] = text_color or THEME.text_accent()
    style["vision"][0] = THEME.vision_accent()

    # Reference line (best same-vision architecture)
    if base_tiny_zs is not None:
        ax.axhline(base_tiny_zs, color="gray", linestyle="--",
                   linewidth=0.7, alpha=0.5, zorder=1)
        ax.text(_WD_BASE + 0.01, base_tiny_zs + 0.05, reference_label,
                ha="left", va="bottom", fontsize=6.5, style="italic",
                color="#666666")

    # Per-scenario label placement to avoid overlap where lines cross the
    # Base--Tiny reference (text and joint nearly coincide at WD 0.75).
    _ann = {"text": (0, 6, "bottom"), "vision": (0, 6, "bottom"),
            "joint": (0, -9, "top")}

    # One line per scenario, all emanating from the shared baseline point
    for scenario in scenarios:
        color, marker, _ = style[scenario]
        pts = abl_df[abl_df["scenario"] == scenario].sort_values("level")
        xs, ys = [], []
        if baseline_zs is not None:
            xs.append(_WD_BASE); ys.append(baseline_zs)
        for lvl in _WD_LEVELS:
            row = pts[np.isclose(pts["level"], lvl)]
            if len(row):
                xs.append(lvl); ys.append(row["zs"].iloc[0])
        if len(xs) < 2:
            continue
        ax.plot(xs, ys, color=color, linewidth=0.9, zorder=3)
        # Markers + value labels for the ablated points (skip the baseline x=0.5)
        dx, dy, va = _ann[scenario]
        for x, y in zip(xs, ys):
            if abs(x - _WD_BASE) < 1e-6:
                continue
            ax.scatter([x], [y], color=color, marker=marker, s=pt_s,
                       edgecolors="white", linewidths=0.3, zorder=4)
            if label_values:
                ax.annotate(f"{y:.1f}", (x, y), textcoords="offset points",
                            xytext=(dx, dy), ha="center", va=va, fontsize=6,
                            color=color, fontweight="bold")

    # Baseline point (Base--Giant, joint WD 0.5) as a shared origin marker
    if baseline_zs is not None:
        ax.scatter([_WD_BASE], [baseline_zs], color="black", marker="*",
                   s=pt_s * 2.2, zorder=5)
        if label_values:
            ax.annotate(f"{baseline_zs:.1f}", (_WD_BASE, baseline_zs),
                        textcoords="offset points", xytext=(-6, 2), ha="right",
                        fontsize=6, fontweight="bold", color="black")
        ax.text(_WD_BASE, baseline_zs - 0.12, baseline_label,
                ha="center", va="top", fontsize=6, color="#333333")

    ax.set_xlabel(r"Weight decay $\lambda$")
    ax.set_ylabel("Avg Performance (%)")
    ax.yaxis.set_major_locator(mpl.ticker.MaxNLocator(integer=True))
    ax.set_xticks([_WD_BASE] + _WD_LEVELS)
    ax.set_xlim(_WD_BASE - 0.08, _WD_LEVELS[-1] + 0.08)
    # Headroom so the top/bottom value labels clear the axes border
    y_all = list(
        abl_df[abl_df["scenario"].isin(list(scenarios) + ["baseline"])]["zs"].dropna()
    )
    if base_tiny_zs is not None:
        y_all.append(base_tiny_zs)
    if y_all:
        ax.set_ylim(min(y_all) - 0.5, max(y_all) + (1.15 if not label_values else 0.6))

    # Legend: one entry per scenario
    from matplotlib.lines import Line2D
    handles = [
        Line2D([0], [0], color=style[s][0], marker=style[s][1], linewidth=0.9,
               markersize=5, markeredgecolor="white", markeredgewidth=0.4,
               label=style[s][2])
        for s in scenarios
    ]
    ax.legend(handles=handles, loc="upper left", framealpha=0.85,
              fontsize=6, handletextpad=0.4, borderpad=0.3, labelspacing=0.3)

    return ax


