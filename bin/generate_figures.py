def _df_zs_bar_panel(ax, data, vcolor, annotate_x=True, show_legend=True):
    """Grouped bar panel: avg zero-shot, degraded (hatched) vs fixed (solid).

    ``annotate_x`` draws the per-group x tick labels + x-axis title (off when a shared
    bottom legend identifies the configs); ``show_legend`` draws the in-panel WD key.
    """
    from matplotlib.patches import Patch
    zs = _degraded_fixed_avg_zs(data)
    visions = [v for v in _DEGRADED_FIXED_VISIONS if v in zs]
    x = np.arange(len(visions))
    w = 0.38
    for i, v in enumerate(visions):
        c = vcolor(v)
        dg, fx = zs[v]["degraded"], zs[v]["fixed"]
        ax.bar(x[i] - w / 2, dg, w, color=c, alpha=0.45, edgecolor="black",
               linewidth=0.6, hatch="////", zorder=3)
        ax.bar(x[i] + w / 2, fx, w, color=c, edgecolor="black", linewidth=0.6, zorder=3)
        if np.isfinite(dg) and np.isfinite(fx):
            ax.annotate(f"+{fx - dg:.1f}", (x[i], max(dg, fx)),
                        textcoords="offset points", xytext=(0, 3), ha="center",
                        fontsize=7, fontweight="bold", color=_darken_color(c))
    ax.set_xticks(x)
    if annotate_x:
        ax.set_xticklabels([f"{v}--Giant" for v in visions], fontsize=7.5,
                           rotation=15, ha="center", rotation_mode="anchor")
        ax.set_xlabel("Architecture")
    else:
        ax.set_xticklabels([])
    ax.set_ylabel("Avg Performance (%)")
    vals = [zs[v][r] for v in visions for r in ("degraded", "fixed") if np.isfinite(zs[v][r])]
    if vals:
        lo, hi = min(vals), max(vals)
        span = hi - lo
        # Truncate the axis (start below the smallest bar) so the +delta
        # differences are visible; leave top room for the single-row legend.
        ax.set_ylim(lo - span * 0.35, hi + span * 0.95)
    if show_legend:
        ax.legend(handles=[
            Patch(facecolor="0.6", alpha=0.45, hatch="////", edgecolor="black", label=_DF_LABEL_DEGRADED),
            Patch(facecolor="0.6", edgecolor="black", label=_DF_LABEL_FIXED),
        ], loc="upper center", ncol=2, fontsize=6.5, framealpha=0.9,
            handlelength=2.0, handleheight=1.5, columnspacing=1.2)


