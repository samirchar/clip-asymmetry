# ── Figure: RankMe heatmap ─────────────────────────────
def _rankme_heatmap(data, pretrain_dataset="cc12m"):
    """Generate RankMe heatmaps (1×2: image | text) for a single dataset.

    Visualises how image and text effective rank vary with encoder sizes.
    The dominant column-wise gradient shows that the text encoder is the
    primary driver of embedding diversity for both modalities.
    """
    bench = data["benchmarks"]
    q = _base_query(data, pretrain_dataset, "zeroshot")
    q_data = bench.query(q)

    fig, axes = plt.subplots(
        1, 2, figsize=(TEXTWIDTH, 4.0),
        gridspec_kw={"wspace": 0.35},
    )
    cmap = plt.get_cmap("YlOrRd")

    # Compute shared colour range across both panels
    all_vals = []
    heatmaps = {}
    name_map_v, name_map_t = {}, {}
    for col in ["image_rankme", "text_rankme"]:
        hm = (
            q_data
            .groupby(["vision_params", "text_params"])
            .agg(val=(col, "first"))
            .reset_index()
            .pivot_table(index="vision_params", columns="text_params", values="val")
            .sort_index(ascending=True)
            .sort_index(axis=1, ascending=True)
        )
        heatmaps[col] = hm
        all_vals.extend(hm.values.ravel())
    global_min, global_max = min(all_vals), max(all_vals)
    global_range = global_max - global_min if global_max != global_min else 1

    name_map_v, name_map_t = _encoder_name_maps(q_data)

    for panel_idx, (ax, col, title) in enumerate(zip(
        axes,
        ["image_rankme", "text_rankme"],
        ["Image RankMe", "Text RankMe"],
    )):
        heatmap_data = heatmaps[col]
        normalized = (heatmap_data - global_min) / global_range

        sns.heatmap(
            normalized, annot=False, cmap=cmap,
            linewidths=0.5, ax=ax, cbar=False,
            vmin=0, vmax=1, square=True,
        )

        for i, row_idx in enumerate(heatmap_data.index):
            row = heatmap_data.loc[row_idx]
            for j, col_idx in enumerate(heatmap_data.columns):
                val = row[col_idx]
                norm_val = normalized.loc[row_idx, col_idx]
                color = "white" if norm_val > 0.45 else "black"
                ax.text(
                    j + 0.5, i + 0.5, f"{val:.0f}",
                    ha="center", va="center",
                    color=color, fontsize=6.5,
                )

        x_labels = _encoder_tick_labels(heatmap_data.columns, name_map_t)
        ax.set_xticklabels(x_labels, rotation=45, ha="right")
        ax.set_xlabel("Text Encoder")
        ax.set_title(title, fontsize=9, pad=4)
        ax.invert_yaxis()

        if panel_idx == 0:
            y_labels = _encoder_tick_labels(heatmap_data.index, name_map_v)
            ax.set_yticklabels(y_labels, rotation=0)
            ax.set_ylabel("Vision Encoder")
        else:
            ax.set_yticklabels([])
            ax.set_ylabel("")

    # Shared colourbar aligned to heatmap height
    norm_obj = mpl.colors.Normalize(vmin=global_min, vmax=global_max)
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm_obj)
    sm.set_array([])
    fig.tight_layout()
    # Position colorbar to match right heatmap
    pos = axes[1].get_position()
    cax = fig.add_axes([pos.x1 + 0.02, pos.y0, 0.015, pos.height])
    cbar = fig.colorbar(sm, cax=cax)
    cbar.set_label("RankMe (effective rank)", fontsize=8)

    label_panels(axes)
    return fig


