if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate paper figures")
    parser.add_argument("--fig", nargs="*", help="Figure names to generate (default: all)")
    parser.add_argument("--list", action="store_true", help="List available figures")
    parser.add_argument("--refresh-wandb", action="store_true",
                        help="Re-fetch training metrics from wandb into data/wandb_cache/ before loading.")
    args = parser.parse_args()

    setup_style()

    if args.refresh_wandb:
        refresh_wandb_cache()

    if args.list:
        data = load_data()
        print("Figures:")
        for name in get_figures(data):
            print(f"  {name}")
        raise SystemExit(0)

    print("Loading data...")
    data = load_data()

    # Generate figures
    figures = get_figures(data)
    targets = args.fig or list(figures.keys())

    for name in targets:
        if name not in figures:
            print(f"✗ {name} — not found (use --list to see available)")
            continue
        print(f"  Generating {name}...", end=" ", flush=True)
        fig = figures[name]()
        save(fig, name)
        plt.close(fig)
        print("✓")

    print(f"\nDone! Figures saved to {FIGURES_DIR}/ and {PAPER_FIGURES_DIR}/")
