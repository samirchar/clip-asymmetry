# ── Asymmetry: bipartite capacity helpers (used by capacity_asymmetry) ──
def _zs_avg_per_config(data, dataset="cc12m"):
    """Avg zero-shot per config, using the paper's canonical aggregation."""
    q = _base_query(data, dataset, "zeroshot")
    return (data["benchmarks"].query(q)
            .groupby(["model", "vision_name", "text_name",
                      "vision_params", "text_params", "total_params"])
            [["preferred_metric_value"]].mean().reset_index())


def _asym_bipartite_panel(ax, data, dataset="cc12m", compact=False):
    """Bipartite graph of the optimal pairings on a shared capacity axis: text
    encoders (left column) and vision encoders (right column), each node placed
    at its own parameter count on a shared log y-axis.

    Two directed edge sets encode the two conditionals: RdPu arrows = best text
    per vision (vision -> its ZS-optimal text), Blues arrows = best vision per
    text (text -> its optimal vision). Because height is capacity, the RdPu
    arrows tilt down (optimal text wants less capacity) and the Blues arrows tilt
    up (optimal vision wants more), and the arrowheads pool near the bottom (text
    optima ~small) and the ceiling (vision optima ~large) -- the asymmetric
    capacity requirement read straight off the vertical gap. ``compact`` uses
    name-only node labels (params are already on the y-axis) for narrow panels.
    """
    from matplotlib.patches import FancyArrowPatch

    g = _zs_avg_per_config(data, dataset)
    g["zs"] = g["preferred_metric_value"] * 100
    best_text = g.loc[g.groupby("vision_params")["zs"].idxmax()]     # vision -> text
    best_vision = g.loc[g.groupby("text_params")["zs"].idxmax()]     # text -> vision

    texts = (g[["text_name", "text_params"]].drop_duplicates()
             .sort_values("text_params").reset_index(drop=True))
    visions = (g[["vision_name", "vision_params"]].drop_duplicates()
               .sort_values("vision_params").reset_index(drop=True))
    # Node y = the encoder's own parameter count on a shared log capacity axis,
    # so height *is* capacity and an edge's tilt shows whether the optimum wants
    # more (up) or less (down) capacity than its partner.
    ty = dict(zip(texts["text_name"], texts["text_params"]))

    # Edge colour = target modality, drawn from the paper's colourmaps.
    to_text_c = plt.get_cmap(THEME.text_cmap)(0.78)     # best text per vision  (-> text)
    to_vision_c = plt.get_cmap(THEME.vision_cmap)(0.78)  # best vision per text  (-> vision)
    node_c = "#e2e2e2"
    node_s = 75 if compact else 115
    lab_dx = 8 if compact else 12

    def edge(xy1, xy2, color, rad):
        ax.add_patch(FancyArrowPatch(xy1, xy2, connectionstyle=f"arc3,rad={rad}",
                                     arrowstyle="-|>", mutation_scale=8,
                                     shrinkA=8, shrinkB=8, color=color, lw=THEME.lw_plot,
                                     alpha=0.9, zorder=2))

    for _, r in best_text.iterrows():   # vision(right) -> text(left), head at text
        edge((1, r["vision_params"]), (0, ty[r["text_name"]]), to_text_c, 0.12)
    for _, r in best_vision.iterrows():  # text(left) -> vision(right), head at vision
        edge((0, ty[r["text_name"]]), (1, r["vision_params"]), to_vision_c, 0.12)

    for _, r in texts.iterrows():
        y = r["text_params"]
        lab = r["text_name"] if compact else f"{r['text_name']} ({r['text_params']/1e6:.0f}M)"
        ax.scatter([0], [y], s=node_s, color=node_c, edgecolor="black", linewidth=0.6, zorder=4)
        ax.annotate(lab, (0, y), xytext=(-lab_dx, 0), textcoords="offset points",
                    ha="right", va="center", fontsize=8)
    for _, r in visions.iterrows():
        y = r["vision_params"]
        name = VISION_NAME_MAP.get(r["vision_name"], r["vision_name"])
        lab = name if compact else f"{name} ({r['vision_params']/1e6:.0f}M)"
        ax.scatter([1], [y], s=node_s, color=node_c, edgecolor="black", linewidth=0.6, zorder=4)
        ax.annotate(lab, (1, y), xytext=(lab_dx, 0), textcoords="offset points",
                    ha="left", va="center", fontsize=8)

    # Column headers in blended coords: x in data (0/1), y in axes fraction.
    from matplotlib.transforms import blended_transform_factory
    htrans = blended_transform_factory(ax.transData, ax.transAxes)
    htext, hvis = ("Text", "Vision") if compact else ("Text encoder", "Vision encoder")
    ax.text(0, 1.02, htext, transform=htrans, ha="center", va="bottom",
            fontsize=9, fontweight="bold")
    ax.text(1, 1.02, hvis, transform=htrans, ha="center", va="bottom",
            fontsize=9, fontweight="bold")

    handles = [mpl.lines.Line2D([], [], color=to_text_c, lw=1.0, marker="<", markersize=4,
                                label="best text per vision"),
               mpl.lines.Line2D([], [], color=to_vision_c, lw=1.0, marker=">", markersize=4,
                                label="best vision per text")]
    lg_y = -0.20 if compact else -0.13
    ax.legend(handles=handles, loc="lower center", bbox_to_anchor=(0.5, lg_y),
              ncol=1, fontsize=7, framealpha=0.9, columnspacing=1.2, handletextpad=0.4,
              labelspacing=0.3)

    ax.set_yscale("log")
    ax.set_ylim(2.2e6, 4.6e8)
    ax.yaxis.set_major_formatter(millions_formatter("M"))
    ax.yaxis.set_minor_formatter(mpl.ticker.NullFormatter())
    ax.set_yticks([3e6, 10e6, 30e6, 100e6, 300e6])
    ax.tick_params(axis="y", labelsize=7)
    ax.set_ylabel("Encoder params (log scale)")
    ax.set_xticks([])
    ax.set_xlim(-0.62, 1.62)
    for side in ("top", "right", "bottom"):
        ax.spines[side].set_visible(False)
    return ax


