def _prior_work_scaling_landscape(transformer=True, lim=(2, 10000)):
    """Vision vs. text encoder size for prior CLIP families (log-log, equal axes).

    Reads ground truth from data/analysis/family_architecture_params.csv. If
    ``transformer`` is True the text axis excludes the token-embedding table
    (text_params - text_embedding_params); otherwise it uses total text params.
    ResNet variants are excluded. Equal axes make the dashed y=x a true diagonal.
    """
    csv_path = FIGURES_DIR.parent / "data" / "analysis" / "family_architecture_params.csv"
    df = pd.read_csv(csv_path)
    df = df[~df["model_name"].str.contains("resnet", case=False)]
    text_col = "text_transformer_params" if transformer else "text_params"

    fig, ax = plt.subplots(figsize=(THEME.textwidth * 0.6, THEME.textwidth * 0.6))
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.plot(list(lim), list(lim), ls="--", color=THEME.grey_mid, lw=THEME.lw_plot, zorder=1)

    handles = []
    for fam in _PRIOR_FAMILIES:
        sub = df[df["model_family"] == fam]
        if sub.empty:
            continue
        dx, dy = _PRIOR_JITTER.get(fam, (0.0, 0.0))
        ax.scatter(sub["vision_params"] / 1e6 * 10**dx, sub[text_col] / 1e6 * 10**dy,
                   marker="o", s=36, color=_PRIOR_COLORS[fam],
                   edgecolor="white", linewidth=0.3, zorder=4)
        handles.append(mpl.lines.Line2D([], [], marker="o", linestyle="none",
                       markerfacecolor=_PRIOR_COLORS[fam], markeredgecolor="white",
                       markersize=7.9, label=_PRIOR_LABELS[fam]))

    ax.set_xlim(*lim)
    ax.set_ylim(*lim)
    ax.set_aspect("equal", adjustable="box")
    ax.legend(handles=handles, fontsize=THEME.fs_legend, loc="center left",
              bbox_to_anchor=(1.01, 0.5), framealpha=0.95)
    fig.tight_layout()
    return fig


