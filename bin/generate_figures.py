# Shared marker list for text encoders (used by both pareto variants)
_TEXT_MARKERS = ["v", "^", "s", "D", "p", "P", "X", "h"]


def _draw_pareto_panel(data, bench, super_task, dataset, ax):
    """Draw a single pareto scatter panel with colour=vision, shape=text."""
    q = _base_query(data, dataset, super_task)
    plot_data = (
        bench.query(q)
        .groupby(["model", "vision_name", "text_name",
                   "vision_params", "text_params", "total_params"])
        [["preferred_metric_value"]].mean().reset_index()
    )

    present_vision = sorted(plot_data["vision_params"].unique())
    present_text = sorted(plot_data["text_params"].unique())
    v_palette = data["vision_palette"]
    v_labels = data["vision_labels"]
    t_labels = data["text_labels"]
    marker_map = {tp: _TEXT_MARKERS[i % len(_TEXT_MARKERS)]
                  for i, tp in enumerate(present_text)}

    # Draw each text encoder group with its marker
    for tp in present_text:
        subset = plot_data[plot_data["text_params"] == tp]
        for vp in present_vision:
            pt = subset[subset["vision_params"] == vp]
            if pt.empty:
                continue
            ax.scatter(
                pt["total_params"], pt["preferred_metric_value"],
                color=v_palette.get(vp, "gray"),
                marker=marker_map[tp], s=25,
                edgecolors="white", linewidths=0.3,
            )

    # Pareto frontier: connect the upper-left non-dominated configs (higher
    # performance for fewer total params) with a light red dotted line.
    front = plot_data.sort_values("total_params")
    keep_x, keep_y, best = [], [], -np.inf
    for _, r in front.iterrows():
        if r["preferred_metric_value"] > best:
            keep_x.append(r["total_params"])
            keep_y.append(r["preferred_metric_value"])
            best = r["preferred_metric_value"]
    if len(keep_x) >= 2:
        ax.plot(keep_x, keep_y, color="#d62728", linestyle=":", linewidth=1.0,
                alpha=0.85, zorder=1)

    # Baseline reference lines (ViT-B-16--Base)
    baseline = plot_data.query('model == "ViT-B-16--Base"')
    if len(baseline):
        ax.axvline(x=baseline["total_params"].values[0], color="gray",
                   linestyle="--", linewidth=0.7, alpha=0.5)
        ax.axhline(y=baseline["preferred_metric_value"].values[0], color="gray",
                   linestyle="--", linewidth=0.7, alpha=0.5)

    ax.set_xlabel("Total Parameters (M)")
    ax.xaxis.set_major_formatter(
        millions_formatter()
    )

    # Build combined legend: colour patches for vision + marker entries for text
    from matplotlib.lines import Line2D
    vision_handles = [
        Line2D([0], [0], marker="o", color="w",
               markerfacecolor=v_palette[vp], markersize=5,
               label=v_labels.get(vp, vp))
        for vp in present_vision if vp in v_palette
    ]
    text_handles = [
        Line2D([0], [0], marker=marker_map[tp], color="gray",
               linestyle="None", markersize=4,
               label=t_labels.get(tp, tp))
        for tp in present_text
    ]
    ax.legend(
        handles=vision_handles + text_handles,
        loc="lower right", framealpha=0.8, fontsize=5.5, ncol=2,
        title="Vision / Text", title_fontsize=6.5,
        handletextpad=0.3, columnspacing=0.8,
    )


def _pareto_scatter_single(data, super_task, pretrain_dataset="cc12m"):
    """Single-panel pareto scatter for one pretrain dataset.

    The legend is split into two vertical blocks (vision = colour, text = shape),
    two markers per row, placed to the right of the plot so the axes stay roughly
    square and the legend text matches the paper's default size.
    """
    bench = data["benchmarks"]
    fig, ax = plt.subplots(figsize=(TEXTWIDTH * 0.74, 2.9))
    _draw_pareto_panel(data, bench, super_task, pretrain_dataset, ax)
    ax.set_ylabel("Avg Performance (%)")
    ax.yaxis.set_major_formatter(mpl.ticker.PercentFormatter(1.0, decimals=0, symbol=None))
    fig.subplots_adjust(left=0.11, right=0.66, top=0.97, bottom=0.14)

    # Single right-hand legend, one marker per row, with "Vision (color)" and
    # "Text (shape)" section headers and a blank spacer between the two groups.
    # labelspacing is tuned so the legend spans the full plot height.
    legend = ax.get_legend()
    if legend:
        handles = legend.legend_handles
        labels = [t.get_text() for t in legend.get_texts()]
        legend.remove()
        n_vision = sum(1 for h in handles if h.get_marker() == "o")
        vision_h, vision_l = handles[:n_vision], labels[:n_vision]
        text_h, text_l = handles[n_vision:], labels[n_vision:]

        from matplotlib.lines import Line2D
        blank = Line2D([], [], color="none")
        header = lambda t: Line2D([], [], color="none", label=t)
        all_h = ([header("Vision (color)")] + vision_h
                 + [blank] + [header("Text (shape)")] + text_h)
        all_l = (["Vision (color)"] + vision_l
                 + [""] + ["Text (shape)"] + text_l)
        leg = ax.legend(
            all_h, all_l, loc="upper left", bbox_to_anchor=(1.02, 1.0),
            ncol=1, fontsize=THEME.fs_legend, framealpha=0.8,
            handletextpad=0.5, labelspacing=0.78, borderaxespad=0.0,
        )
        leg._legend_box.align = "left"
    return fig


