def _df_draw_pair_arrow(ax, dg, fx, color):
    """Straight degraded→fixed arrow (skipped if either endpoint is missing/non-finite)."""
    if dg is None or fx is None or not np.all(np.isfinite([*dg, *fx])):
        return
    ax.annotate("", xy=fx, xytext=dg, zorder=4, arrowprops=dict(
        arrowstyle="-|>", color=color, lw=THEME.lw_plot, alpha=0.9, shrinkA=3, shrinkB=3))


def _df_draw_marker(ax, x, y, marker, color):
    """degraded/fixed marker with a white halo so stacked markers stay distinct."""
    ax.scatter(x, y, marker=marker, s=THEME.scatter_area, color=color, edgecolor="black",
               linewidth=0.6, zorder=5, path_effects=_DF_MARKER_HALO)


