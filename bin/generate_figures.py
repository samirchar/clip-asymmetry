def _geometry_landscape_plot(data, probe="mscoco_captions"):
    """Predicted zero-shot over the (image uniformity, alignment) plane.

    Background is the full-data (not leave-one-out) 2-predictor fit; the grid
    models are overlaid as markers by vision encoder. The best text pairing per
    vision (highest observed avg zero-shot) is highlighted, and a zoom inset
    magnifies the dense large-vision cluster.
    """
    df = _load_geometry_fig_data()
    d = df[df["probe"] == probe].dropna(subset=["image_uniformity", "alignment", "zs_obs"])
    X = d[["image_uniformity", "alignment"]].values
    y = d["zs_obs"].values
    mu, sd = X.mean(0), X.std(0)
    beta = np.linalg.lstsq(
        np.column_stack([np.ones(len(y)), (X - mu) / sd]), y, rcond=None)[0]

    ug_min, ug_max = d.image_uniformity.min(), d.image_uniformity.max()
    ag_min, ag_max = d.alignment.min(), d.alignment.max()
    upad = 0.05 * (ug_max - ug_min)
    apad = 0.05 * (ag_max - ag_min)
    ug = np.linspace(ug_min - upad, ug_max + upad, 200)
    ag = np.linspace(ag_min - apad, ag_max + apad, 200)
    UU, AA = np.meshgrid(ug, ag)
    grid_pts = np.column_stack([UU.ravel(), AA.ravel()])
    ZZ = (np.column_stack([np.ones(len(grid_pts)), (grid_pts - mu) / sd]) @ beta).reshape(UU.shape)
    vmin, vmax = ZZ.min(), ZZ.max()

    grid = d[d["kind"] == "grid"]
    order = grid.drop_duplicates("vision_name").sort_values("vision_params")["vision_name"].tolist()
    best_idx = grid.loc[grid.groupby("vision_name")["zs_obs"].idxmax()].index

    def _draw_markers(axis):
        for vis in order:
            mk = _GEOMETRY_VISION_MARKERS.get(vis, "o")
            s = grid[grid["vision_name"] == vis]
            reg = s[~s.index.isin(best_idx)]
            axis.scatter(reg.image_uniformity, reg.alignment, marker=mk, c="white",
                         edgecolor="black", linewidth=0.5, s=26, zorder=3)
            bst = s[s.index.isin(best_idx)]
            axis.scatter(bst.image_uniformity, bst.alignment, marker=mk, c="white",
                         edgecolor=_PRED_COLOR, linewidth=1.7, s=44, zorder=4)

    fig, ax = plt.subplots(figsize=(TEXTWIDTH * 0.633, 3.01))
    hm = ax.pcolormesh(UU, AA, ZZ, cmap="viridis", shading="auto", vmin=vmin, vmax=vmax)
    fig.colorbar(hm, ax=ax).set_label("Predicted avg performance (%)", fontsize=THEME.fs_label)
    _draw_markers(ax)
    ax.set_xlim(ug.min(), ug.max()); ax.set_ylim(ag.min(), ag.max())
    ax.set_xlabel("Image Uniformity", fontsize=THEME.fs_label)
    ax.set_ylabel("Alignment", fontsize=THEME.fs_label)

    # Zoom inset over the region holding the dense cluster AND every best-per-vision
    # marker, placed over the empty corner.
    focus = grid[grid.index.isin(best_idx)
                 | (grid.image_uniformity < ug_min + 0.08 * (ug_max - ug_min))]
    x0, x1 = focus.image_uniformity.min(), focus.image_uniformity.max()
    y0, y1 = focus.alignment.min(), focus.alignment.max()
    xpad = 0.06 * (x1 - x0) + 0.005
    ypad = 0.10 * (y1 - y0) + 0.005
    axins = ax.inset_axes([0.58, 0.58, 0.40, 0.40])
    axins.pcolormesh(UU, AA, ZZ, cmap="viridis", shading="auto", vmin=vmin, vmax=vmax)
    _draw_markers(axins)
    axins.set_xlim(x0 - xpad, x1 + xpad)
    axins.set_ylim(y0 - ypad, y1 + ypad)
    axins.set_xticks([]); axins.set_yticks([])
    ax.indicate_inset_zoom(axins, edgecolor="black", alpha=0.7)

    handles = [mpl.lines.Line2D([], [], marker=_GEOMETRY_VISION_MARKERS[v], color="none",
               markerfacecolor="white", markeredgecolor="black", markersize=6, label=v)
               for v in order]
    handles.append(mpl.lines.Line2D([], [], marker="o", color="none", markerfacecolor="white",
                   markeredgecolor=_PRED_COLOR, markeredgewidth=1.7, markersize=6,
                   label="Best per vision"))
    ax.legend(handles=handles, fontsize=THEME.fs_legend, framealpha=0.9, loc="lower left",
              title="Vision encoder", title_fontsize=THEME.fs_legend_title, ncol=2)
    fig.tight_layout()
    return fig


